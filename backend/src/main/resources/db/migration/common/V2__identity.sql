-- V2: users, roles, tokens (E2 Identity & RBAC). Roles follow the ERD in the plan.
CREATE TABLE roles (
    id   INT PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL
);
INSERT INTO roles (id, code, name) VALUES
